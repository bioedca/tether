"""Contract tests for the Windows launch environment the installer writes (issue #553).

``packaging/scripts/post_install.bat`` writes ``launchers\\tether.bat`` and
``launchers\\tether-gui.bat``, the Start Menu shortcut (ADR-0051, ADR-0094) and the "Tether
Command Prompt" shortcut with the script it runs (issue #666). They only
run on a real Windows install, so the packaging install-smoke exercises them there; these
tests pin what the script writes and what the smoke runs, on every platform the unit matrix
covers.
"""

from __future__ import annotations

import re
from pathlib import Path

_SCRIPTS = Path(__file__).resolve().parents[1] / "packaging" / "scripts"
INSTALL_SMOKE_SCRIPT = _SCRIPTS / "install_smoke.sh"
POST_INSTALL_BAT = _SCRIPTS / "post_install.bat"
PRE_UNINSTALL_BAT = _SCRIPTS / "pre_uninstall.bat"


def _install_smoke_code_lines() -> str:
    """The smoke script's non-comment lines, joined (as ``test_marker_contract`` reads it)."""
    return "\n".join(
        ln
        for ln in INSTALL_SMOKE_SCRIPT.read_text(encoding="utf-8").splitlines()
        if not ln.lstrip().startswith("#")
    )


#: The folders ``conda activate`` puts at the front of PATH on Windows, in its order.
_WIN_ACTIVATION_DIRS = (
    "%ENV_D%",
    r"%ENV_D%\Library\mingw-w64\bin",
    r"%ENV_D%\Library\usr\bin",
    r"%ENV_D%\Library\bin",
    r"%ENV_D%\Scripts",
    r"%ENV_D%\bin",
)

#: The exact last line of each launcher, as ``post_install.bat`` echoes it (issue #747).
#: The CLI launcher runs ``tether.exe`` in the same console; the GUI launcher hands off to
#: the console-less ``tether-gui.exe`` with ``start ""`` (the empty title), so the console
#: the Start Menu shortcut opens can close. ``%%*`` writes a literal ``%*``: every argument
#: the launcher gets is forwarded. The install-smoke runs ``tether.bat`` but only checks
#: that ``tether-gui.bat`` exists, so this is the one place the GUI line is pinned.
_LAUNCHER_START_LINES = {
    "tether.bat": r'"%ENV_D%\Scripts\tether.exe" %%*',
    "tether-gui.bat": r'start "" "%ENV_D%\Scripts\tether-gui.exe" %%*',
}


def _bat_code(text: str) -> str:
    """A batch script's lines minus its ``rem`` comments."""
    return "\n".join(ln for ln in text.splitlines() if not ln.lstrip().lower().startswith("rem"))


def _shortcut_block(text: str, lnk_var: str) -> str:
    """The PowerShell call that saves the shortcut at ``$env:<lnk_var>``, up to its ``Save``."""
    start = text.index(f"CreateShortcut($env:{lnk_var})")
    return text[start : text.index('"$s.Save()"', start)]


def test_windows_launchers_put_the_env_folders_first_on_path() -> None:
    """Both Windows launchers activate the env's PATH for their own process (issue #553).

    rc2's ``tether.bat`` ran ``tether.exe`` with the user's PATH unchanged, so MKL resolved
    its dependent DLLs through the ordinary search order and crashed with 0xC06D007F at
    the first BLAS call on a PC with other scientific software. The fix is what
    ``conda activate`` does: the env's folders first. ``setlocal`` keeps the change to the
    launcher's own process, and the literal ``%PATH%`` (written as ``%%PATH%%``) keeps the
    user's PATH, read at launch time, after them; nothing edits the persistent PATH.
    """
    text = POST_INSTALL_BAT.read_text(encoding="utf-8")
    env_path = re.search(r'(?m)^set "ENV_PATH=([^"]*)"$', text)
    assert env_path, 'post_install.bat must define `set "ENV_PATH=..."`'
    assert tuple(env_path.group(1).split(";")) == _WIN_ACTIVATION_DIRS, (
        "ENV_PATH must list the env's activation folders in `conda activate` order; "
        f"got {env_path.group(1)}"
    )
    assert re.search(r'(?m)^set "ENV_D=%PREFIX%\\envs\\tether"$', text)
    for launcher, start_line in _LAUNCHER_START_LINES.items():
        lines = [
            ln.split(" echo ", 1)[1]
            for ln in text.splitlines()
            if re.match(r'>>?\s*"%LAUNCH_D%\\' + re.escape(launcher) + '"', ln)
        ]
        header = ["@echo off", "rem Generated by the Tether installer (ADR-0051, issue #553)."]
        assert lines[:2] == header, lines
        body = lines[2:]
        assert body[:2] == ["setlocal", 'set "PATH=%ENV_PATH%;%%PATH%%"'], (
            f"{launcher} must `setlocal`, then put ENV_PATH ahead of the user's PATH, "
            f"before it starts anything; got {body}"
        )
        assert body[2:] == [start_line], (
            f"{launcher} must end by starting its own exe and forwarding every argument "
            f"(`%%*`); expected {start_line!r}, got {body[2:]}"
        )
    assert "setx" not in "\n".join(
        ln for ln in text.splitlines() if not ln.lstrip().lower().startswith("rem")
    ), "the installer must never edit the user's persistent PATH (ADR-0051)"


def test_windows_shortcut_starts_the_console_less_gui_exe_directly() -> None:
    """The Start Menu shortcut targets ``tether-gui.exe`` itself (issue #579, ADR-0076).

    rc3's shortcut ran ``tether-gui.bat`` through ``cmd.exe`` (issues #553 and #578), so a
    console window flashed before the GUI opened. The GUI now puts the env's folders first
    on its own ``PATH`` at startup (``tests/test_gui_env_path.py``), so the shortcut can run
    the console-less pip launcher with no ``cmd.exe``, no ``.bat`` and empty arguments. Start
    lists a shortcut whose target is an ``.exe``; it did not list one aimed at the ``.bat``
    (issue #578). The shortcut still shows the Tether ``tether.ico`` rather than the generic
    launcher's icon (issue #673; ``tests/test_gui_identity.py`` binds the path).
    """
    text = POST_INSTALL_BAT.read_text(encoding="utf-8")
    assert re.search(r'(?m)^set "TETHER_GUI_EXE=%ENV_D%\\Scripts\\tether-gui\.exe"$', text)
    gui = _shortcut_block(text, "TETHER_LNK")
    assert '"$s.TargetPath=$env:TETHER_GUI_EXE;"' in gui
    assert len(re.findall(r"\$s\.TargetPath=", gui)) == 1, "one shortcut, one target"
    code = _bat_code(gui)
    # Only the Tether Command Prompt (issue #666) may run cmd.exe; the GUI shortcut never.
    assert "CMD_EXE" not in code and "cmd.exe" not in code.lower()
    # Cleared, not just left unset: CreateShortcut OPENS an existing .lnk, and rc3's still
    # carries `/c ""<bat>""`, which tether-gui.exe's parser would reject (Codex, PR #827).
    assert re.findall(r"\$s\.Arguments=[^;]*;", code) == ["$s.Arguments='';"], (
        "the shortcut must set its arguments to empty, so an rc3 shortcut loses /c"
    )
    assert "TETHER_GUI_BAT" not in _bat_code(text)
    assert "\"$s.IconLocation=$env:TETHER_ICO + ',0';\"" in text


def test_windows_shortcut_opens_a_normal_window() -> None:
    """``WindowStyle`` is 1, a normal window, not 7, minimized (issue #579).

    Style 7 minimized the ``.bat``'s console. With the GUI as the target it would minimize
    the GUI: the pip launcher hands its startup info to ``pythonw``, and Windows applies the
    shortcut's style to the first window the process shows, which is the splash.
    """
    text = POST_INSTALL_BAT.read_text(encoding="utf-8")
    assert '"$s.WindowStyle=1;"' in text
    assert '"$s.WindowStyle=7;"' not in text


def test_windows_install_smoke_runs_blas_through_the_launcher() -> None:
    """The Windows smoke drives a BLAS-calling extraction through ``tether.bat`` (issue #553).

    ``--version`` touches no BLAS, which is how rc2's smoke stayed green while every real
    extraction crashed on a user's PC.
    """
    code = _install_smoke_code_lines()
    launch = 'cmd /c "$prefix\\\\launchers\\\\tether.bat" extract '
    movie = "docs\\\\tutorial\\\\data\\\\tutorial_movie.tif"
    assert launch + movie in code, (
        "install_smoke.sh must run `tether.bat extract` on the committed tutorial movie"
    )
    assert 'test -f "$(cygpath -u "$smoke_project")"' in code


def test_windows_install_smoke_installs_over_an_rc3_shortcut() -> None:
    """The smoke seeds an rc3-format shortcut before installing (issue #579, PR #827).

    ``CreateShortcut`` opens an existing ``.lnk``, so a field the installer does not set
    keeps the earlier install's value. rc3's shortcut ran ``cmd.exe`` with ``/c`` arguments;
    seeding one first makes the smoke's read-back of target, arguments and style prove the
    installer overwrites every field.
    """
    code = _install_smoke_code_lines()
    seed = code.index('$s.Arguments = "/c')
    install = code.index('cmd /c "$(cygpath -w "$exe") /S /D=$prefix"')
    readback = code.index("*'\\envs\\tether\\Scripts\\tether-gui.exe||1')")
    assert seed < install < readback


def _prompt_script_lines(text: str) -> list[str]:
    """The lines ``post_install.bat`` echoes into ``tether-prompt.bat``, as written there."""
    return [
        ln.split(" echo ", 1)[1]
        for ln in text.splitlines()
        if re.match(r'>>?\s*"%PROMPT_BAT%"', ln)
    ]


def test_tether_command_prompt_script_adds_only_the_launcher_folder() -> None:
    """``tether-prompt.bat`` puts the launcher folder first, for the console only (issue #666).

    The doubled percent signs in ``post_install.bat`` write single ones into the script:
    ``%PATH%`` is the console's own PATH, read when the shortcut opens, and ``%%V`` is the
    ``for`` variable. No ``setlocal``: the change must outlive the script and stay in the
    console ``cmd /k`` keeps open. Only ``%LAUNCH_D%`` is added, never the prefix root or its
    ``Scripts`` and ``Library`` folders, which hold the bootstrap python, pip and conda
    (issue #492). The script is in the prefix root, so the launcher folder keeps only the
    two launchers (ADR-0094; the install smoke checks that folder's contents).
    """
    text = POST_INSTALL_BAT.read_text(encoding="utf-8")
    assert re.search(r'(?m)^set "PROMPT_BAT=%PREFIX%\\tether-prompt\.bat"$', text)
    assert re.search(r'(?m)^set "LAUNCH_D=%PREFIX%\\launchers"$', text)
    assert _prompt_script_lines(text) == [
        "@echo off",
        "rem Generated by the Tether installer for the Tether Command Prompt (issue #666).",
        'set "PATH=%LAUNCH_D%;%%PATH%%"',
        "for /f \"delims=\" %%%%V in ('tether --version') do echo %%%%V - "
        'type "tether --help" to see the commands.',
    ]
    # The script is written after the launchers exist, so its first `tether` finds one.
    assert text.index('> "%LAUNCH_D%\\tether.bat"') < text.index('> "%PROMPT_BAT%"')


def test_tether_command_prompt_shortcut_runs_cmd_on_the_script() -> None:
    """The second Start Menu shortcut opens ``cmd.exe /k`` on the script (issue #666).

    cmd.exe is named by its absolute path (the installer's PATH is not the user's, issue
    #551), and Start lists the shortcut because its target is an ``.exe`` (issue #578). The
    script path sits in two pairs of quotes, built from ``[char]34`` so no quote has to cross
    the command line into PowerShell: cmd removes the outer pair and keeps a path with spaces
    whole. The paths reach PowerShell through the environment, never inside its source.
    """
    text = POST_INSTALL_BAT.read_text(encoding="utf-8")
    assert re.search(r'(?m)^set "PROMPT_LNK=%SM_D%\\Tether Command Prompt\.lnk"$', text), (
        "the shortcut is named Tether Command Prompt and sits beside Tether.lnk"
    )
    assert re.search(r'(?m)^set "PROMPT_CMD_EXE=%SystemRoot%\\System32\\cmd\.exe"$', text), (
        "cmd.exe is named by its absolute path"
    )
    prompt = _shortcut_block(text, "PROMPT_LNK")
    assert '"$s.TargetPath=$env:PROMPT_CMD_EXE;"' in prompt
    assert "\"$s.Arguments='/k '+$q+$q+$env:PROMPT_BAT+$q+$q;\"" in prompt
    assert '"$q=[char]34;"' in text[: text.index("CreateShortcut($env:PROMPT_LNK)")]
    assert '"$s.WorkingDirectory=$env:USERPROFILE;"' in prompt
    assert '"$s.WindowStyle=1;"' in prompt
    assert "\"$s.IconLocation=$env:TETHER_ICO + ',0';\"" in prompt
    # The prompt shortcut is made after the GUI shortcut and before the wheels go.
    assert (
        text.index("CreateShortcut($env:TETHER_LNK)")
        < text.index("CreateShortcut($env:PROMPT_LNK)")
        < text.index('del "%WHEELHOUSE%')
    )
    assert "setx" not in _bat_code(text) and "reg add" not in _bat_code(text).lower()


def test_pre_uninstall_removes_the_tether_command_prompt_shortcut() -> None:
    """Uninstalling removes the second shortcut too, before the folder (issue #666)."""
    code = _bat_code(PRE_UNINSTALL_BAT.read_text(encoding="utf-8")).splitlines()
    lnk = '"%SM_D%\\Tether Command Prompt.lnk"'
    delete = f"if exist {lnk} del /f /q {lnk}"
    assert delete in code
    rmdir = next(i for i, ln in enumerate(code) if "rmdir" in ln)
    assert code.index(delete) < rmdir, "delete the shortcut before removing its folder"


def test_windows_install_smoke_checks_the_tether_command_prompt() -> None:
    """The Windows smoke reads the shortcut and runs ``tether`` the way it does (issue #666).

    It checks the shortcut exists and what it runs, the welcome line, ``tether --version``
    in that console, and that the console's PATH gained the launcher folder and nothing
    else. Uninstall comes after, and its existing check that the Start Menu folder is gone
    fails if the second shortcut is left behind.
    """
    code = _install_smoke_code_lines()
    for needle in (
        'prompt_lnk="$sm_dir/Tether Command Prompt.lnk"',
        'test -f "$prompt_lnk"',
        'prompt_bat="$prefix\\\\tether-prompt.bat"',
        'cmd /c "call $prompt_bat >nul && tether --version"',
        'cmd /v:on /c "call $prompt_bat >nul && echo !PATH!"',
        "added == {norm(os.path.join(prefix, 'launchers'))}",
    ):
        assert needle in code, needle
    assert code.index('test -f "$prompt_lnk"') < code.index("Uninstall-Tether.exe")
    assert 'test ! -e "$sm_dir"' in code
