"""Contract tests for the Windows launch environment the installer writes (issue #553).

``packaging/scripts/post_install.bat`` writes ``bin\\tether.bat`` and ``bin\\tether-gui.bat``
and the Start Menu shortcut (ADR-0051). They only run on a real Windows install, so the
packaging install-smoke exercises them there; these tests pin what the script writes and
what the smoke runs, on every platform the unit matrix covers.
"""

from __future__ import annotations

import re
from pathlib import Path

_SCRIPTS = Path(__file__).resolve().parents[1] / "packaging" / "scripts"
INSTALL_SMOKE_SCRIPT = _SCRIPTS / "install_smoke.sh"
POST_INSTALL_BAT = _SCRIPTS / "post_install.bat"


def _install_smoke_code_lines() -> str:
    """The smoke script's non-comment lines, joined (as ``test_marker_contract`` reads it)."""
    return "\n".join(
        ln
        for ln in INSTALL_SMOKE_SCRIPT.read_text(encoding="utf-8").splitlines()
        if not ln.lstrip().startswith("#")
    )


#: The folders ``conda activate`` puts at the front of PATH on Windows, in its order.
_WIN_ACTIVATION_DIRS = (
    "%ENV_D%",
    r"%ENV_D%\Library\mingw-w64\bin",
    r"%ENV_D%\Library\usr\bin",
    r"%ENV_D%\Library\bin",
    r"%ENV_D%\Scripts",
    r"%ENV_D%\bin",
)


def test_windows_launchers_put_the_env_folders_first_on_path() -> None:
    """Both Windows launchers activate the env's PATH for their own process (issue #553).

    rc2's ``tether.bat`` ran ``tether.exe`` with the user's PATH unchanged, so MKL resolved
    its dependent DLLs through the ordinary search order and crashed with 0xC06D007F at
    the first BLAS call on a PC with other scientific software. The fix is what
    ``conda activate`` does: the env's folders first. ``setlocal`` keeps the change to the
    launcher's own process, and the literal ``%PATH%`` (written as ``%%PATH%%``) keeps the
    user's PATH, read at launch time, after them; nothing edits the persistent PATH.
    """
    text = POST_INSTALL_BAT.read_text(encoding="utf-8")
    env_path = re.search(r'(?m)^set "ENV_PATH=([^"]*)"$', text)
    assert env_path, 'post_install.bat must define `set "ENV_PATH=..."`'
    assert tuple(env_path.group(1).split(";")) == _WIN_ACTIVATION_DIRS, (
        "ENV_PATH must list the env's activation folders in `conda activate` order; "
        f"got {env_path.group(1)}"
    )
    assert re.search(r'(?m)^set "ENV_D=%PREFIX%\\envs\\tether"$', text)
    for launcher in ("tether.bat", "tether-gui.bat"):
        lines = [
            ln.split(" echo ", 1)[1]
            for ln in text.splitlines()
            if re.match(r'>>?\s*"%BIN_D%\\' + re.escape(launcher) + '"', ln)
        ]
        header = ["@echo off", "rem Generated by the Tether installer (ADR-0051, issue #553)."]
        assert lines[:2] == header, lines
        body = lines[2:]
        assert body[:2] == ["setlocal", 'set "PATH=%ENV_PATH%;%%PATH%%"'], (
            f"{launcher} must `setlocal`, then put ENV_PATH ahead of the user's PATH, "
            f"before it starts anything; got {body}"
        )
        assert len(body) == 3 and "%ENV_D%\\Scripts\\" in body[2], body
    assert "setx" not in "\n".join(
        ln for ln in text.splitlines() if not ln.lstrip().lower().startswith("rem")
    ), "the installer must never edit the user's persistent PATH (ADR-0051)"


def test_windows_shortcut_starts_the_gui_through_its_launcher() -> None:
    """The Start Menu route gets the launcher's PATH too (issue #553).

    A ``.lnk`` cannot set environment variables, so targeting ``tether-gui.exe`` directly
    would start the GUI without the env's folders on PATH. It targets ``tether-gui.bat``,
    minimized (``WindowStyle`` 7), and borrows the console-less exe's icon.
    """
    text = POST_INSTALL_BAT.read_text(encoding="utf-8")
    assert re.search(r'(?m)^set "TETHER_GUI_BAT=%BIN_D%\\tether-gui\.bat"$', text)
    assert '"$s.TargetPath=$env:TETHER_GUI_BAT;"' in text
    assert '"$s.TargetPath=$env:TETHER_GUI_EXE;"' not in text
    assert '"$s.WindowStyle=7;"' in text
    assert "\"$s.IconLocation=$env:TETHER_GUI_EXE + ',0';\"" in text


def test_windows_install_smoke_runs_blas_through_the_launcher() -> None:
    """The Windows smoke drives a BLAS-calling extraction through ``tether.bat`` (issue #553).

    ``--version`` touches no BLAS, which is how rc2's smoke stayed green while every real
    extraction crashed on a user's PC.
    """
    code = _install_smoke_code_lines()
    launch = 'cmd /c "$prefix\\\\bin\\\\tether.bat" extract '
    movie = "docs\\\\tutorial\\\\data\\\\tutorial_movie.tif"
    assert launch + movie in code, (
        "install_smoke.sh must run `tether.bat extract` on the committed tutorial movie"
    )
    assert 'test -f "$(cygpath -u "$smoke_project")"' in code
