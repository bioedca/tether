"""The consensus HMM fits of Campos-Chavez et al. 2024 fitted again in the sidecar (#757, ADR-0106).

The paper fitted each sample with tMAVEN. Its Source Data archive (ADR-0083, manifest id
``campos2024-source-data``) holds what a fit needs and what it found:

* the trace matrices (``smFRET_SourceData/*.txt``, donor and acceptor columns in turn);
* for each fit, a FRET histogram sheet that pools the frames the fit read, and a transition
  density sheet whose transitions run between the idealized levels, that is the state means;
* for the five global fits, the count matrix tMAVEN wrote (``Kmatrix/*.txt``).

``campos_chavez_2024_hmm.json`` holds the settings of each fit with their source in the article
and, generated by ``python tests/_campos_chavez_hmm.py windows ARCHIVE``, the frames of each
molecule that each histogram pools. This module builds the SMD of a fit from them, fits it in a
child process (``_campos_chavez_hmm_child.py``) and compares the model with the published values.
``python tests/_campos_chavez_hmm.py measure ARCHIVE`` prints every deviation for seeds 0 to 9
and 757; that is how ``schema/campos_chavez_hmm_limits.json`` was measured.

Nothing of the archive is written into the repository; the SMD files go to a temporary directory.
"""

from __future__ import annotations

import io
import json
import os
import re
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

import numpy as np

from _kinsoft_measured import read_workbook

HERE = Path(__file__).resolve().parent
SETTINGS = HERE / "reference_data" / "campos_chavez_2024_hmm.json"
LIMITS = HERE.parent / "schema" / "campos_chavez_hmm_limits.json"
CHILD = HERE / "_campos_chavez_hmm_child.py"
RUNNER = HERE.parent / "src" / "tether" / "idealize" / "_sidecar_runner.py"
WORKBOOK = "MainFigures-AllCombined.xlsx"
EPS = float(np.finfo(np.float64).eps)
#: The deviations a fit is held to, in the order the limits file and the docs table give them.
METRICS = ("means_max_abs", "populations_max_abs", "offdiag_counts_l1_rel", "tdp_counts_l1_rel")


def load_settings() -> dict:
    """The committed settings, sources and windows of every fit."""
    return json.loads(SETTINGS.read_text(encoding="utf-8"))


def load_limits() -> dict:
    return json.loads(LIMITS.read_text(encoding="utf-8"))


# --- reading the archive -------------------------------------------------------------------------


def read_book(archive: Path) -> dict[str, list[tuple]]:
    """Every sheet of the main-figure workbook, read from a temporary copy of the member."""
    with zipfile.ZipFile(archive) as zf, tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / WORKBOOK
        path.write_bytes(zf.read(WORKBOOK))
        return read_workbook(path)


def read_traces(archive: Path, name: str) -> tuple[np.ndarray, np.ndarray]:
    """``(donor, acceptor)`` of a trace matrix, each ``(frames, molecules)``."""
    with zipfile.ZipFile(archive) as zf:
        m = np.loadtxt(io.BytesIO(zf.read(f"smFRET_SourceData/{name}.txt")))
    return m[:, 0::2], m[:, 1::2]


def read_kmatrix(archive: Path, name: str) -> np.ndarray:
    with zipfile.ZipFile(archive) as zf:
        return np.loadtxt(
            io.BytesIO(zf.read(f"ErrorCalculations_CodeAndSourceData/Kmatrix/{name}.txt"))
        )


def column(rows: list[tuple], header: str, col: int) -> np.ndarray:
    """The numbers below the first cell ``header`` of column ``col``, down to the first gap."""
    start = next(i for i, r in enumerate(rows) if len(r) > col and r[col] == header) + 1
    out = []
    for r in rows[start:]:
        v = r[col] if len(r) > col else None
        if not isinstance(v, float):
            break
        out.append(v)
    return np.asarray(out, dtype=np.float64)


def efficiency(donor: np.ndarray, acceptor: np.ndarray) -> np.ndarray:
    with np.errstate(divide="ignore", invalid="ignore"):
        return acceptor / (donor + acceptor)


def rounding_bound(donor: np.ndarray, acceptor: np.ndarray) -> np.ndarray:
    """Largest change of ``A / (D + A)`` that writing ``D`` and ``A`` as ``%.7e`` can cause.

    The same first-order bound as #756 (ADR-0097): half a unit in the 8th digit of each
    intensity, plus two machine epsilons for the division.
    """

    def half_unit(x: np.ndarray) -> np.ndarray:
        a = np.abs(x)
        return 0.5 * 10.0 ** (np.floor(np.log10(np.where(a > 0, a, 1.0))) - 7)

    with np.errstate(divide="ignore", invalid="ignore"):
        total = donor + acceptor
        spread = np.abs(donor) * half_unit(acceptor) + np.abs(acceptor) * half_unit(donor)
        return spread / total**2 + 2 * EPS * np.abs(acceptor / total)


# --- the published values ------------------------------------------------------------------------


def published(fit: dict, book: dict, archive: Path) -> dict:
    """State means, transition counts and (global fits) the count matrix the paper published."""
    rows = book[fit["tdp_sheet"]]
    initial = column(rows, "Initial E_FRET", 0)
    final = column(rows, "Final E_FRET", 1)
    means = np.unique(np.r_[initial, final])
    out = {"means": means, "tdp_counts": pair_counts(initial, final, means)}
    if fit.get("kmatrix"):
        k = read_kmatrix(archive, fit["kmatrix"])
        order = np.asarray(fit["kmatrix_order"])
        out["counts"] = k[np.ix_(order, order)]
    return out


def pair_counts(initial: np.ndarray, final: np.ndarray, means: np.ndarray) -> np.ndarray:
    """Transitions from level ``i`` to level ``j``, each level matched to its nearest mean."""
    n = means.size
    a = np.argmin(np.abs(initial[:, None] - means[None, :]), axis=1)
    b = np.argmin(np.abs(final[:, None] - means[None, :]), axis=1)
    counts = np.zeros((n, n), dtype=np.int64)
    np.add.at(counts, (a, b), 1)
    return counts


# --- the windows ---------------------------------------------------------------------------------


def find_windows(e: np.ndarray, bound: np.ndarray, values: np.ndarray) -> list[list[int]]:
    """Locate the pooled values of a histogram sheet, as ``[molecule, first, frames, offset]``.

    From the first unplaced value on, every frame of every molecule within ``bound`` of it is a
    start, and the longest run of following frames that matches the following values is taken
    (the search of #756's ``find_windows``). A value no frame matches is skipped. A run of one
    frame is not a window: an HMM needs two frames, and a single matching frame is a chance hit.
    """
    frames = e.shape[0]
    flat, flat_bound = e.T.ravel(), bound.T.ravel()
    order = np.argsort(flat)
    ordered = flat[order]
    reach = float(np.nanmax(flat_bound[np.isfinite(flat)]))
    windows: list[list[int]] = []
    pos = 0
    while pos < values.size:
        v = values[pos]
        lo, hi = np.searchsorted(ordered, [v - reach, v + reach])
        best = (-1, -1, 1)
        for k in order[lo:hi]:
            if not abs(flat[k] - v) <= flat_bound[k]:
                continue
            mol, first = divmod(int(k), frames)
            n = min(frames - first, values.size - pos)
            seg = slice(first, first + n)
            bad = ~(np.abs(e[seg, mol] - values[pos : pos + n]) <= bound[seg, mol])
            run = int(np.argmax(bad)) if bad.any() else n
            if run > best[2]:
                best = (mol, first, run)
        if best[0] >= 0:
            windows.append([best[0], best[1], best[2], pos])
        pos += best[2]
    return windows


def make_windows(archive: Path) -> dict:
    """The windows of every fit, for the settings file."""
    settings = load_settings()
    book = read_book(archive)
    out = {}
    for key, fit in settings["fits"].items():
        d, a = read_traces(archive, fit["matrix"])
        values = column(book[fit["histogram_sheet"]], "FRET Efficiency", 0)
        win = find_windows(efficiency(d, a), rounding_bound(d, a), values)
        out[key] = {
            "values": int(values.size),
            "unplaced": int(values.size - sum(w[2] for w in win)),
            "windows": sorted(win),
        }
    return out


def check_windows(fit: dict, book: dict, archive: Path) -> dict:
    """Each committed window against the histogram sheet: it must be the published values."""
    d, a = read_traces(archive, fit["matrix"])
    e, bound = efficiency(d, a), rounding_bound(d, a)
    values = column(book[fit["histogram_sheet"]], "FRET Efficiency", 0)
    ratio, placed = 0.0, 0
    for mol, first, n, offset in fit["windows"]["windows"]:
        seg = slice(first, first + n)
        dev = np.abs(e[seg, mol] - values[offset : offset + n]) / bound[seg, mol]
        ratio = max(ratio, float(np.max(dev)))
        placed += n
    return {"values": int(values.size), "placed": placed, "max_bound_ratio": ratio}


# --- the fit -------------------------------------------------------------------------------------


def molecules(fit: dict) -> list[tuple[int, int, int]]:
    """``(molecule, pre, post)`` of every fitted molecule, in matrix order."""
    return [(m, f, f + n) for m, f, n, _ in sorted(fit["windows"]["windows"])]


def write_fit_smd(fit: dict, archive: Path, path: Path) -> Path:
    """An SMD of the fitted molecules with each molecule's window as its tMAVEN pre/post."""
    from tether.idealize import write_smd

    d, a = read_traces(archive, fit["matrix"])
    mols = molecules(fit)
    raw = np.stack([np.stack([d[:, m], a[:, m]], axis=1) for m, _, _ in mols])
    return write_smd(
        path,
        raw,
        pre_list=[p for _, p, _ in mols],
        post_list=[q for _, _, q in mols],
        description=f"Campos-Chavez 2024 {fit['matrix']}",
    )


def run_fit(
    fit: dict,
    smd: Path,
    seed: int,
    *,
    python: str | os.PathLike[str] | None = None,
    model_key: str | None = None,
    timeout: float = 1800.0,
):
    """Fit ``smd`` in the sidecar with the settings of ``fit``; returns the ``StateModel``.

    ``python`` defaults to ``$TETHER_SIDECAR_PYTHON``. ``model_key`` overrides the model key of
    ``fit`` (the ``vbgmm_vbhmm`` report). The child applies ``fit["prefs"]`` on top of tMAVEN's
    defaults, so every setting the article gives is set and every other one stays tMAVEN's.
    """
    from tether.idealize.driver import read_model

    python = python or os.environ["TETHER_SIDECAR_PYTHON"]
    out = smd.with_name(f"{smd.stem}.{model_key or fit['model_key']}.{seed}.model.hdf5")
    cmd = [
        str(python),
        str(CHILD),
        str(RUNNER),
        str(smd),
        "dataset",
        model_key or fit["model_key"],
        str(fit["nstates"]),
        str(out),
        str(seed),
        json.dumps(fit["prefs"]),
    ]
    env = {**os.environ, "QT_QPA_PLATFORM": "offscreen", "NAPARI_ASYNC": "0"}
    proc = subprocess.run(cmd, capture_output=True, text=True, env=env, timeout=timeout)
    if proc.returncode != 0:
        raise RuntimeError(f"sidecar fit failed\n{proc.stdout[-2000:]}\n{proc.stderr[-2000:]}")
    return read_model(out)


# --- the comparison ------------------------------------------------------------------------------


def idealized_counts(model, means: np.ndarray) -> np.ndarray:
    """Transitions of the model's idealized paths, each level matched to its nearest ``means``."""
    initial, final = [], []
    for path in model.idealized:
        path = path[np.isfinite(path)]
        change = np.flatnonzero(path[1:] != path[:-1])
        initial.append(path[change])
        final.append(path[change + 1])
    return pair_counts(np.concatenate(initial), np.concatenate(final), means)


def compare(model, pub: dict) -> dict:
    """The deviations of one fresh model from the published values of its fit."""
    order = np.argsort(model.means)
    means = model.means[order]
    out: dict = {"nstates": int(model.nstates), "means": means.tolist()}
    off = ~np.eye(pub["means"].size, dtype=bool)
    if means.size != pub["means"].size:
        out["state_count_differs"] = True
        return out
    out["means_max_abs"] = float(np.max(np.abs(means - pub["means"])))
    # Each idealized level is a fitted mean, so matching it to the sorted fitted means gives its
    # state; states then pair with the published ones by rank, one to one.
    tdp = idealized_counts(model, means)
    out["tdp_counts_l1_rel"] = float(
        np.abs(tdp - pub["tdp_counts"])[off].sum() / pub["tdp_counts"][off].sum()
    )
    out["populations_max_abs"] = None
    out["offdiag_counts_l1_rel"] = None
    if "counts" in pub and model.tmatrix is not None:
        counts = model.tmatrix[np.ix_(order, order)]
        share = counts.sum(axis=1) / counts.sum()
        pub_share = pub["counts"].sum(axis=1) / pub["counts"].sum()
        out["populations"] = share.tolist()
        out["populations_max_abs"] = float(np.max(np.abs(share - pub_share)))
        dev = np.abs(counts - pub["counts"])[off].sum() / pub["counts"][off].sum()
        out["offdiag_counts_l1_rel"] = float(dev)
        out["counts"] = counts.tolist()
    elif model.frac is not None:
        out["populations"] = np.asarray(model.frac)[order].tolist()
    return out


def measure(archive: Path, seeds, python: str | None = None, keys=None) -> dict:
    """Every deviation of every fit for each seed (the evidence of the limits file)."""
    settings = load_settings()
    book = read_book(archive)
    out: dict = {}
    with tempfile.TemporaryDirectory() as tmp:
        for key, fit in settings["fits"].items():
            if keys and key not in keys:
                continue
            pub = published(fit, book, archive)
            smd = write_fit_smd(fit, archive, Path(tmp) / f"{key}.smd.hdf5")
            out[key] = {str(s): compare(run_fit(fit, smd, s, python=python), pub) for s in seeds}
            print(key, json.dumps(out[key]), file=sys.stderr, flush=True)
    return out


# --- the stored files of the workstation leg (step 4) ---------------------------------------------


def parse_summary(text: str) -> dict | None:
    """The model of a tMAVEN report (``make_report``): type, traces, states, means, counts."""
    found = {
        k: re.search(p, text)
        for k, p in {
            "type": r"Model type = (.+)",
            "traces": r"Model ran on (\d+) traces",
            "nstates": r"nstates = (\d+)",
            "means": r"means = \[([^\]]*)\]",
        }.items()
    }
    if not all(found.values()):
        return None
    nstates = int(found["nstates"].group(1))
    out = {
        "type": found["type"].group(1).strip(),
        "traces": int(found["traces"].group(1)),
        "means": np.array([float(x) for x in found["means"].group(1).split()]),
        "counts": None,
    }
    tm = re.search(r"tmatrix = \s*\[(.*?)\]\]", text, re.S)
    if tm:
        numbers = np.array([float(x) for x in re.findall(r"[-+0-9.eE]+", tm.group(1))])
        if numbers.size == nstates * nstates:
            out["counts"] = numbers.reshape(nstates, nstates)
    return out


def fit_of(nstates: int, traces: int) -> str | None:
    """The one fit with this number of states and of traces, or ``None``."""
    fits = load_settings()["fits"]
    hits = [
        k
        for k, f in fits.items()
        if f["nstates"] == nstates and len(f["windows"]["windows"]) == traces
    ]
    return hits[0] if len(hits) == 1 else None


if __name__ == "__main__":
    cmd, archive = sys.argv[1], Path(sys.argv[2])
    if cmd == "windows":
        print(json.dumps(make_windows(archive)))
    elif cmd == "measure":
        keys = sys.argv[4].split(",") if len(sys.argv) > 4 else None
        python = sys.argv[3] if len(sys.argv) > 3 and sys.argv[3] != "-" else None
        print(json.dumps(measure(archive, [*range(10), 757], python, keys), indent=1))
    else:
        raise SystemExit(f"unknown command {cmd!r}")
