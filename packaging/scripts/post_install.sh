# constructor post_install (Unix: Linux .sh + macOS .pkg) — ADR-0049, PRD §9 M9.
#
# Runs AFTER all conda packages and the bundled wheels are linked into the prefix.
# It offline-installs the three non-conda wheels (no network: --no-index --no-deps;
# every runtime dependency already comes from the bundled conda envs) and wires the
# isolated sidecar interpreter for conda-activated launches. POSIX sh only.
#
# Both runtime stacks are constructor `extra_envs` (ADR-0049): the GUI/`tether`
# stack lives in envs/tether, the tMAVEN sidecar in envs/sidecar. `base` is only the
# python+conda bootstrap that constructor requires for extra_envs — nothing app is
# installed there.
set -e

WHEELHOUSE="$PREFIX/wheelhouse"
TETHER_PY="$PREFIX/envs/tether/bin/python"
SIDECAR_PY="$PREFIX/envs/sidecar/bin/python"

# tether wheel -> the GUI env (PySide6/napari/current-numpy).
"$TETHER_PY" -m pip install --no-index --no-deps "$WHEELHOUSE"/tether-*.whl

# setuptools<81 -> the sidecar env, BEFORE tMAVEN. tMAVEN's `maven_class.__init__`
# does `import pkg_resources`, which setuptools DEPRECATED by 80.9.0 (still shipped
# through 81.0.0) and REMOVED in 82.0.0, and the sidecar lock resolves setuptools 82.0.1
# — so without this the env builds cleanly and then dies at the first idealization
# (issue #212). `<81` rather than `<82` is the bound that setuptools' own deprecation
# warning names ("pin to Setuptools<81"). scripts/setup_sidecar.py applies the same pin on
# the source path, reading the version and its sha256 from
# packaging/setuptools-compatibility.txt; this is the installer's equivalent, using the
# wheel that file's hash-checked download staged.
#
# pip is given the wheel by PATH, not by requirement spec, so it downgrades the conda
# setuptools rather than reporting "already satisfied". Ordering is deliberate: tMAVEN's
# wheel is already built, so nothing here needs pkg_resources at install time, but
# putting the pin first means the sidecar is never momentarily in the broken state.
"$SIDECAR_PY" -m pip install --no-index --no-deps "$WHEELHOUSE"/setuptools-*.whl

# tMAVEN wheel -> the ISOLATED sidecar env (PyQt5/numpy<2); never the GUI env.
"$SIDECAR_PY" -m pip install --no-index --no-deps "$WHEELHOUSE"/tmaven-*.whl

# Best-effort: point the app at its bundled sidecar interpreter when the GUI env is
# conda-activated (tether.idealize.driver reads $TETHER_SIDECAR_PYTHON). envs/sidecar
# is a sibling of envs/tether, so resolve it relative to $CONDA_PREFIX at activation
# time (the heredoc is single-quoted, so the expansion is deferred, not baked in). A
# prefix-relative app-side default is the more robust follow-up (ADR-0049).
ACT_D="$PREFIX/envs/tether/etc/conda/activate.d"
mkdir -p "$ACT_D"
cat > "$ACT_D/tether-sidecar.sh" <<'EOF'
export TETHER_SIDECAR_PYTHON="$(dirname "$CONDA_PREFIX")/sidecar/bin/python"
EOF

# --- Launchers (ADR-0051) --------------------------------------------------------
# envs/tether/bin is NEVER on PATH: initialize_conda/initialize_by_default are false,
# so the installer deliberately does not touch the user's shell. Without the shims
# below there is no way to start Tether except by typing an env-relative absolute
# path, and `tether --version` — the documented install-verification step — fails.
#
# One stable, documented directory ($PREFIX/bin) holds both launchers, so the install
# guide can name a SINGLE path to put on PATH. The installer does not edit PATH
# itself: `setx` silently truncates PATH beyond 1024 characters on Windows, and
# rewriting a user's shell rc is equally invasive. Adding the directory is a
# documented one-liner; breaking someone's PATH is not recoverable by documentation.
BIN_D="$PREFIX/bin"
mkdir -p "$BIN_D"
for _cmd in tether tether-gui; do
  cat > "$BIN_D/$_cmd" <<EOF
#!/bin/sh
# Generated by the Tether installer (ADR-0051). Forwards to the pinned GUI env.
exec "$PREFIX/envs/tether/bin/$_cmd" "\$@"
EOF
  chmod +x "$BIN_D/$_cmd"
done

# macOS application bundle (issue #663, ADR-0091): Tether.app in ~/Applications for an
# install inside the home folder, else in /Applications, so that Launchpad, Spotlight and
# the Dock find "Tether". The bundle is a launcher only: its executable is a sh script that
# execs envs/tether/bin/tether-gui, and it holds no copy of the environment.
# tether.gui.macos_app writes it with plistlib, so the Info.plist is valid by
# construction, and the install smoke runs the same module's `check`. A Tether.app that
# the module did not write is left in place. Nothing removes the bundle on uninstall
# (constructor's pre_uninstall is Windows-only), so docs/install.md names it.
if [ "$(uname -s)" = "Darwin" ]; then
  TETHER_USER_APPS_NEW=""
  [ -d "$HOME/Applications" ] || TETHER_USER_APPS_NEW=1
  TETHER_APP="$("$TETHER_PY" -m tether.gui.macos_app install --prefix "$PREFIX")"
  if [ -n "$TETHER_APP" ]; then
    # An administrator install runs this script as root: give a bundle in the user's
    # own Applications folder back to the user, as constructor does for the prefix,
    # and the folder too when this step created it, so the user can remove the bundle
    # without sudo. A folder that was there before keeps its owner.
    if [ "$(id -u)" = "0" ] && [ -n "${USER:-}" ]; then
      case "$TETHER_APP" in
        "$HOME"/*)
          chown -R "$USER" "$TETHER_APP" || true
          if [ -n "$TETHER_USER_APPS_NEW" ] && [ -d "$HOME/Applications" ]; then
            chown "$USER" "$HOME/Applications" || true
          fi
          ;;
      esac
    fi
    # Best-effort: register the bundle now, so Spotlight and Launchpad need not wait
    # for the next scan of the folder.
    LSREGISTER=/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister
    if [ -x "$LSREGISTER" ]; then
      "$LSREGISTER" -f "$TETHER_APP" >/dev/null 2>&1 || true
    fi
    # Best-effort: ask Spotlight to index the bundle now. Spotlight still indexes the new
    # install folder first, so on a real Mac it listed Tether after about ten minutes.
    if [ -x /usr/bin/mdimport ]; then
      /usr/bin/mdimport "$TETHER_APP" >/dev/null 2>&1 || true
    fi
  fi
fi

# Linux desktop entry so the shell is launchable from the applications menu.
# `uname` rather than a constructor selector: this is one shared script.
# Exec= is quoted below: the freedesktop spec splits that value on whitespace, so an
# unquoted prefix containing a space would launch the wrong executable.
#
# The entry's icon (issue #673). Icon=tether is a theme name, not a path, so the icon
# files go into the user's own hicolor tree, the folder every desktop searches for it.
# They are copied from the installed wheel (tether.gui.identity.hicolor_dir), so this
# script and the package can never name different sizes. docs/install.md lists every
# file this adds, for the uninstall. StartupWMClass=Tether matches the window class Qt
# sets on X11 (the application name); on Wayland the window names tether.desktop itself
# (QGuiApplication.setDesktopFileName), and the menu entry then gives the icon.
if [ "$(uname -s)" = "Linux" ]; then
  APPS_D="$HOME/.local/share/applications"
  ICONS_D="$HOME/.local/share/icons/hicolor"
  ICON_SRC="$("$TETHER_PY" -c 'from tether.gui.identity import hicolor_dir; print(hicolor_dir())')"
  for _src in "$ICON_SRC"/*/apps/tether.png "$ICON_SRC"/scalable/apps/tether.svg; do
    _rel="${_src#"$ICON_SRC"/}"
    mkdir -p "$ICONS_D/${_rel%/*}"
    cp "$_src" "$ICONS_D/$_rel"
  done
  # Best-effort: GTK and Qt ignore an icon-theme.cache that is older than its theme
  # folder, and adding a file to an existing size folder does not change that folder's
  # time. So touch the theme folder, and rebuild a cache only where one already exists:
  # creating one would add a file to the user's tree that the uninstall does not remove.
  touch "$ICONS_D"
  if [ -f "$ICONS_D/icon-theme.cache" ] && command -v gtk-update-icon-cache >/dev/null 2>&1; then
    gtk-update-icon-cache -q -t -f "$ICONS_D" >/dev/null 2>&1 || true
  fi
  mkdir -p "$APPS_D"
  cat > "$APPS_D/tether.desktop" <<EOF
[Desktop Entry]
Type=Application
Name=Tether
GenericName=single-molecule FRET analysis
Comment=Provenance-first smFRET extraction, curation and analysis
Exec="$PREFIX/envs/tether/bin/tether-gui" %f
Icon=tether
StartupWMClass=Tether
Terminal=false
Categories=Science;Biology;Education;
MimeType=application/x-tether;
EOF
  # Best-effort: a stale cache hides a brand-new entry until the next login.
  if command -v update-desktop-database >/dev/null 2>&1; then
    update-desktop-database "$APPS_D" >/dev/null 2>&1 || true
  fi
fi

# Drop the staged wheels; the environments now own the installed packages.
rm -f "$WHEELHOUSE"/tether-*.whl "$WHEELHOUSE"/tmaven-*.whl "$WHEELHOUSE"/setuptools-*.whl
